const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('installer', {
  getCatalog: () => ipcRenderer.invoke('catalog:get'),
  getCatalogDetails: () => ipcRenderer.invoke('catalog-details:get'),
  getComponentCatalog: () => ipcRenderer.invoke('components:get'),
  getClaudeStatus: () => ipcRenderer.invoke('claude:status'),
  runDiagnostics: () => ipcRenderer.invoke('diagnostics:run'),
  exportDiagnosticReport: (payload) => ipcRenderer.invoke('diagnostics:export', payload),
  getUpdateStatus: () => ipcRenderer.invoke('updates:get-status'),
  downloadAvailableUpdate: () => ipcRenderer.invoke('updates:download'),
  installDownloadedUpdate: () => ipcRenderer.invoke('updates:install'),
  openPublishedRelease: () => ipcRenderer.invoke('updates:open-release'),
  getTerminalPreference: () => ipcRenderer.invoke('terminal:get-preference'),
  setTerminalPreference: (payload) => ipcRenderer.invoke('terminal:set-preference', payload),
  testTerminalPreference: () => ipcRenderer.invoke('terminal:test-preference'),
  runClaudeCode: (payload) => ipcRenderer.invoke('claude:run', payload),
  reviewClaudeRemoval: () => ipcRenderer.invoke('claude:review-removal'),
  applyClaudeRemoval: (payload) => ipcRenderer.invoke('claude:apply-removal', payload),
  installClaudeOnly: () => ipcRenderer.invoke('claude:install-only'),
  verifySetup: () => ipcRenderer.invoke('setup:verify'),
  runCompleteSetup: (payload) => ipcRenderer.invoke('setup:complete', payload),
  runInstall: (payload) => ipcRenderer.invoke('install:run', payload),
  chooseComponentProject: () => ipcRenderer.invoke('components:choose-project'),
  previewComponents: (payload) => ipcRenderer.invoke('components:preview', payload),
  installComponents: (payload) => ipcRenderer.invoke('components:install', payload),
  reportAnonymousSetupSuccess: (payload) => ipcRenderer.invoke('telemetry:report-setup-success', payload),
  getCompassStatus: () => ipcRenderer.invoke('compass:status'),
  askCompass: (payload) => ipcRenderer.invoke('compass:ask', payload),
  chooseSetupManagerProject: () => ipcRenderer.invoke('setup-manager:choose-project'),
  discoverSetup: (payload) => ipcRenderer.invoke('setup-manager:discover', payload),
  chooseCustomSource: () => ipcRenderer.invoke('setup-manager:choose-custom-source'),
  reviewCustomAddOn: (payload) => ipcRenderer.invoke('setup-manager:review-custom', payload),
  applyCustomAddOn: (payload) => ipcRenderer.invoke('setup-manager:apply-custom', payload),
  reviewCleanup: (payload) => ipcRenderer.invoke('setup-manager:review-cleanup', payload),
  applyCleanup: (payload) => ipcRenderer.invoke('setup-manager:apply-cleanup', payload),
  reviewAllDuplicates: (payload) => ipcRenderer.invoke('setup-manager:review-all-duplicates', payload),
  applyAllDuplicates: (payload) => ipcRenderer.invoke('setup-manager:apply-all-duplicates', payload),
  reviewAllSkillBackups: (payload) => ipcRenderer.invoke('setup-manager:review-all-skill-backups', payload),
  applyAllSkillBackups: (payload) => ipcRenderer.invoke('setup-manager:apply-all-skill-backups', payload),
  reviewSkillBackupReplacement: (payload) => ipcRenderer.invoke('setup-manager:review-skill-backup-replacement', payload),
  applySkillBackupReplacement: (payload) => ipcRenderer.invoke('setup-manager:apply-skill-backup-replacement', payload),
  reviewPluginChange: (payload) => ipcRenderer.invoke('setup-manager:review-plugin-change', payload),
  applyPluginChange: (payload) => ipcRenderer.invoke('setup-manager:apply-plugin-change', payload),
  reviewProjectPackageRemoval: (payload) => ipcRenderer.invoke('setup-manager:review-project-package-removal', payload),
  applyProjectPackageRemoval: (payload) => ipcRenderer.invoke('setup-manager:apply-project-package-removal', payload),
  reviewManagedExtrasRemoval: () => ipcRenderer.invoke('setup-manager:review-managed-extras-removal'),
  applyManagedExtrasRemoval: (payload) => ipcRenderer.invoke('setup-manager:apply-managed-extras-removal', payload),
  reviewAppUninstall: () => ipcRenderer.invoke('app:review-uninstall'),
  exportInstallationManifest: () => ipcRenderer.invoke('app:export-installation-manifest'),
  openManifestFolder: () => ipcRenderer.invoke('app:open-manifest-folder'),
  getManifestVerificationCommand: () => ipcRenderer.invoke('app:get-manifest-verification-command'),
  verifyInstallationManifest: () => ipcRenderer.invoke('app:verify-installation-manifest'),
  verifyDroppedInstallationManifest: (file) => {
    try {
      const filePath = webUtils.getPathForFile(file);
      return filePath
        ? ipcRenderer.invoke('app:verify-dropped-installation-manifest', { filePath })
        : Promise.resolve({ ok: false, error: 'Drop a saved manifest file from your computer.' });
    } catch {
      return Promise.resolve({ ok: false, error: 'Drop a saved manifest file from your computer.' });
    }
  },
  compareInstallationManifests: () => ipcRenderer.invoke('app:compare-installation-manifests'),
  applyAppUninstall: (payload) => ipcRenderer.invoke('app:apply-uninstall', payload),
  onOutput: (callback) => ipcRenderer.on('installer:output', (_event, payload) => callback(payload)),
  onState: (callback) => ipcRenderer.on('installer:state', (_event, payload) => callback(payload)),
  onComponentOutput: (callback) => ipcRenderer.on('component:output', (_event, payload) => callback(payload)),
  onComponentState: (callback) => ipcRenderer.on('component:state', (_event, payload) => callback(payload)),
  onUpdateStatus: (callback) => ipcRenderer.on('updates:status', (_event, payload) => callback(payload)),
});
